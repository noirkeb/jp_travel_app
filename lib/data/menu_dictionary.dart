  // 긴 용어부터 치환해야 정확 (예: '唐揚げ定食' 먼저, 그다음 '定食')
  static final List<MapEntry<String, String>> _sorted = terms.entries.toList()
    ..sort((a, b) => b.key.length.compareTo(a.key.length));

  // 히라가나·가타카나·한자 등 일본어 문자 감지
  static final RegExp _japanese =
      RegExp(r'[぀-ヿ㐀-䶿一-鿿ｦ-ﾟ]');

  /// 사전만으로 완역되면 한국어 문자열, 아니면 null(=Google 번역에 위임).
  static String? tryTranslate(String ja) {
    var s = ja;
    for (final e in _sorted) {
      if (s.contains(e.key)) {
        s = s.replaceAll(e.key, ' ${e.value} ');
      }
    }
    s = s.replaceAll(RegExp(r'\s+'), ' ').trim();
    // "980 엔" -> "980엔", "5 개" -> "5개" 처럼 숫자와 단위를 붙여 자연스럽게
    s = s.replaceAllMapped(RegExp(r'(\d)\s+(엔|개)'), (m) => '${m[1]}${m[2]}');
    if (s.isEmpty) return null;
    if (_japanese.hasMatch(s)) return null; // 일본어가 남으면 사전으로 부족
    return s;
  }
