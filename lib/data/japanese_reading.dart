  static final List<MapEntry<String, String>> _sorted = readings.entries.toList()
    ..sort((a, b) => b.key.length.compareTo(a.key.length));

  static final RegExp _japanese =
      RegExp(r'[぀-ヿ㐀-䶿一-鿿ｦ-ﾟ]');

  /// 일본어 문자열을 한글 발음으로 변환. 사전에 없는 부분은 그대로 남는다.
  static String toReading(String ja) {
    var s = ja;
    for (final e in _sorted) {
      if (s.contains(e.key)) {
        s = s.replaceAll(e.key, ' ${e.value} ');
      }
    }
    return s.replaceAll(RegExp(r'\s+'), ' ').trim();
  }

  static bool hasJapanese(String s) => _japanese.hasMatch(s);
